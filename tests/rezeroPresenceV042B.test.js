import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {
  createPresence, beginPresence, advancePresence, PRESENCE_START_X,
  PRESENCE_DOOR_X, PHASES
} from '../src/rezero/presence.js';

function stepFor(p, seconds, options) {
  const events=[];
  for(let i=0;i<Math.round(seconds/.04);i++){
    events.push(...advancePresence(p,.04,options));
  }
  return events;
}

test('presence stays dormant until the CCTV discrepancy is documented',()=>{
  const p=createPresence();
  assert.equal(p.phase,'dormant');
  assert.equal(stepFor(p,50,{cameraVisible:true}).length,0);
  assert.equal(p.x,PRESENCE_START_X);
  assert.equal(beginPresence(p),true);
  assert.equal(beginPresence(p),false,'repeated evidence must not restart the scene');
});

test('silhouette waits long enough to be noticed in actual CAM 01',()=>{
  const p=createPresence();beginPresence(p);
  stepFor(p,10,{cameraVisible:false,doorClosed:true});
  assert.equal(p.phase,'watch');
  assert.equal(p.x,PRESENCE_START_X);
  stepFor(p,2.1,{cameraVisible:true,doorClosed:true});
  assert.equal(p.phase,'approach');
});

test('player leaving CCTV early does not soft-lock the sequence',()=>{
  const p=createPresence();beginPresence(p);
  stepFor(p,30.2,{cameraVisible:false,doorClosed:true});
  assert.equal(p.phase,'approach');
});

test('same actor traverses the existing corridor without teleports or instant attacks',()=>{
  const p=createPresence();beginPresence(p);
  const events=[];
  const phases=[];
  let previousX=p.x;
  for(let i=0;i<1100;i++){
    const result=advancePresence(p,.04,{cameraVisible:true,doorClosed:true});
    events.push(...result);
    if(phases.at(-1)!==p.phase)phases.push(p.phase);
    if(p.phase==='approach')assert.ok(p.x<=previousX+.001,'approach jumped backward');
    if(p.phase==='withdraw')assert.ok(p.x>=previousX-.001,'withdraw jumped forward');
    assert.ok(Math.abs(p.x-previousX)<.09,'impossible per-frame teleport');
    previousX=p.x;
    if(p.phase==='departed')break;
  }
  assert.equal(p.phase,'departed');
  assert.ok(p.x>=PRESENCE_DOOR_X);
  assert.ok(events.some(e=>e.type==='step'),'footsteps must be generated by actual travel');
  assert.equal(events.filter(e=>e.type==='handle').length,1);
  assert.ok(events.some(e=>e.type==='leave'));
  for(const x of ['watch','approach','doorstep','withdraw','departed']) assert.ok(phases.includes(x));
  assert.ok(PHASES.includes(p.phase));
});

test('an open doorway suppresses impossible closed-door handle animation',()=>{
  const p=createPresence();beginPresence(p);
  const events=[];
  for(let i=0;i<1000;i++){
    events.push(...advancePresence(p,.04,{cameraVisible:true,doorClosed:false}));
    if(p.phase==='departed')break;
  }
  assert.ok(!events.some(x=>x.type==='handle'));
  assert.equal(p.handleTurn,0);
});

test('physically entering the same corridor may register one real glimpse',()=>{
  const p=createPresence();beginPresence(p);
  let glimpses=0;
  for(let i=0;i<1000;i++){
    const result=advancePresence(p,.04,{
      cameraVisible:true,doorClosed:true,
      player:{x:6,z:1.48}
    });
    glimpses+=result.filter(x=>x.type==='glimpse').length;
    if(p.phase==='departed')break;
  }
  assert.equal(glimpses,1);
});

test('visual actor, sound, handle and CCTV all use the same shared presence state',()=>{
  const source=readFileSync('src/rezero/FirstRoom.jsx','utf8');
  assert.match(source,/function PresenceActor\(/);
  assert.match(source,/advanceEncounter\(p,rawDt/);
  assert.match(source,/beginPresence\(presence\.current\)/);
  assert.match(source,/ref=\{actor\}/);
  assert.match(source,/soundAt\(ev\.x,ev\.z/);
  assert.match(source,/presence\.current\.handleTurn/);
  assert.match(source,/cameraVisible=\{panel==='camera' && selectedFeed!=='cam2'\}/);
  assert.match(source,/onPresencePhase=\{setPresencePhase\}/);
});
